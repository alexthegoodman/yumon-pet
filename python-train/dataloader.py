import os
import struct
import json
import time
from typing import Optional, List, Tuple, Dict, Any
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader
import zstandard
from tokenizers import Tokenizer


MAGIC = b"YUMONSMP"
PAD_TOKEN = 0
BOS_TOKEN = 1
EOS_TOKEN = 2


def load_samples_cache(
    cache_path: str,
    max_samples: Optional[int] = None,
) -> Tuple[Dict[str, Any], List[Tuple[Tuple[int, ...], Tuple[int, ...]]]]:
    """
    Fast streaming loader for samples.bin generated by Rust cache_samples.
    Reads zstandard-compressed StoredSample records and extracts (input_ids, target_labels).
    """
    if not os.path.exists(cache_path):
        raise FileNotFoundError(f"Sample cache not found at: {cache_path}")

    start_time = time.time()
    with open(cache_path, "rb") as f:
        magic = f.read(8)
        if magic != MAGIC:
            raise ValueError(f"Invalid magic header: {magic!r}, expected {MAGIC!r}")

        header_len = struct.unpack("<I", f.read(4))[0]
        header_bytes = f.read(header_len)
        metadata = json.loads(header_bytes.decode("utf-8"))

        dctx = zstandard.ZstdDecompressor()
        reader = dctx.stream_reader(f)
        uncompressed = reader.read()

    mv = memoryview(uncompressed)
    pos = 0
    total_samples = metadata.get("samples", 0)
    limit = min(total_samples, max_samples) if max_samples is not None else total_samples

    samples: List[Tuple[Tuple[int, ...], Tuple[int, ...]]] = []
    samples_append = samples.append

    for _ in range(limit):
        # input_ids: u64 count followed by count * u32
        n_in = struct.unpack_from("<Q", mv, pos)[0]
        pos += 8
        in_ids = struct.unpack_from(f"<{n_in}I", mv, pos)
        pos += n_in * 4

        # target_labels: u64 count followed by count * u32
        n_tgt = struct.unpack_from("<Q", mv, pos)[0]
        pos += 8
        tgt_ids = struct.unpack_from(f"<{n_tgt}I", mv, pos)
        pos += n_tgt * 4

        # action (u32), motion_dir (u32)
        pos += 8

        # world: 3 entities (each: 1 byte is_some, if is_some: 4 bytes dir + 4 bytes dist)
        for _ in range(3):
            is_some = mv[pos]
            pos += 1
            if is_some:
                pos += 8

        # target_json string
        l_json = struct.unpack_from("<Q", mv, pos)[0]
        pos += 8 + l_json

        # pair strings (p0, p1)
        l_p0 = struct.unpack_from("<Q", mv, pos)[0]
        pos += 8 + l_p0
        l_p1 = struct.unpack_from("<Q", mv, pos)[0]
        pos += 8 + l_p1

        samples_append((in_ids, tgt_ids))

    elapsed = time.time() - start_time
    print(
        f"[SampleCache] Loaded {len(samples)} samples from {cache_path} "
        f"(version {metadata.get('version')}, max_seq_len {metadata.get('max_seq_len')}) "
        f"in {elapsed:.2f}s"
    )
    return metadata, samples


class YumonPetDataset(Dataset):
    """
    Dataset preparing causal prompt-separator-reply sequences matching Burn's build_moe_batch:
      - Prompt tokens from sample[0]
      - Separator tokens (e.g. space ' ') if not plain text
      - Reply tokens from sample[1]
      - Loss targets shifted by 1 with loss applied only to separator + reply tokens
      - Unsupervised prompt tokens and padding positions are assigned PAD_TOKEN (0)
    """
    def __init__(
        self,
        samples: List[Tuple[Tuple[int, ...], Tuple[int, ...]]],
        max_seq_len: int = 256,
        sep_tokens: Optional[List[int]] = None,
    ):
        self.samples = samples
        self.max_seq_len = max_seq_len
        # Default space separator [146] for 16k BPE tokenizer
        self.sep_tokens = [146] if sep_tokens is None else sep_tokens
        self.sep_len = len(self.sep_tokens)

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        in_ids, tgt_ids = self.samples[idx]

        # Plain text has <= 1 input tokens (no prompt), full sequence is in target
        is_plain = len(in_ids) <= 1
        sep = [] if is_plain else self.sep_tokens
        sep_len = len(sep)

        input_len = min(len(in_ids), self.max_seq_len - sep_len - 1)
        target_len = len(tgt_ids)

        # Build full sequence: [input] + [sep] + [target]
        full_seq = list(in_ids[:input_len]) + sep
        remaining = max(0, self.max_seq_len - len(full_seq))
        actual_target_len = min(target_len, remaining)
        full_seq.extend(tgt_ids[:actual_target_len])

        # Right pad to max_seq_len
        seq_len = len(full_seq)
        if seq_len < self.max_seq_len:
            full_seq.extend([PAD_TOKEN] * (self.max_seq_len - seq_len))
        else:
            full_seq = full_seq[: self.max_seq_len]

        # Shifted targets for causal next-token prediction
        # Predict tokens starting from input_len - 1 (the last prompt token predicts the first sep/target token)
        loss_targets = [PAD_TOKEN] * self.max_seq_len
        start_idx = max(0, input_len - 1)
        end_idx = min(self.max_seq_len - 1, input_len + sep_len + actual_target_len - 1)

        for i in range(start_idx, end_idx):
            loss_targets[i] = full_seq[i + 1]

        return torch.tensor(full_seq, dtype=torch.long), torch.tensor(loss_targets, dtype=torch.long)


def trim_batch_collate(batch: List[Tuple[torch.Tensor, torch.Tensor]]) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Collate function with dynamic batch trimming.
    Trims all sequences in the batch down to the batch's longest active position,
    matching Rust's trim_batch optimization.
    """
    seqs, targets = zip(*batch)
    seqs = torch.stack(seqs, dim=0)       # [B, max_seq_len]
    targets = torch.stack(targets, dim=0) # [B, max_seq_len]

    # Find longest active token across sequences and targets
    non_pad = (seqs != PAD_TOKEN) | (targets != PAD_TOKEN)
    if non_pad.any():
        max_active_len = int(non_pad.sum(dim=-1).max().item())
        max_active_len = max(max_active_len, 2)
        seqs = seqs[:, :max_active_len]
        targets = targets[:, :max_active_len]

    return seqs, targets


def get_dataloaders(
    cache_path: str,
    tokenizer_path: Optional[str] = None,
    batch_size: int = 16,
    max_seq_len: int = 256,
    val_fraction: float = 0.01,
    max_samples: Optional[int] = None,
    seed: int = 4815162342,
    num_workers: int = 0,
) -> Tuple[DataLoader, DataLoader, Dict[str, Any]]:
    """
    Load samples from samples.bin and return (train_loader, val_loader, metadata).
    """
    meta, all_samples = load_samples_cache(cache_path, max_samples=max_samples)

    # Determine separator tokens from tokenizer if available
    sep_tokens = [146]  # default space token ID
    if tokenizer_path and os.path.exists(tokenizer_path):
        try:
            tok = Tokenizer.from_file(tokenizer_path)
            encoded_space = tok.encode(" ", add_special_tokens=False).ids
            if encoded_space:
                sep_tokens = encoded_space
        except Exception as e:
            print(f"Warning: could not resolve space token from {tokenizer_path}: {e}")

    # Shuffle with seed and split train/val
    rng = np.random.default_rng(seed)
    indices = np.arange(len(all_samples))
    rng.shuffle(indices)

    val_count = max(1, min(int(len(all_samples) * val_fraction), 2000))
    val_indices = indices[:val_count]
    train_indices = indices[val_count:]

    train_samples = [all_samples[i] for i in train_indices]
    val_samples = [all_samples[i] for i in val_indices]

    train_dataset = YumonPetDataset(train_samples, max_seq_len=max_seq_len, sep_tokens=sep_tokens)
    val_dataset = YumonPetDataset(val_samples, max_seq_len=max_seq_len, sep_tokens=sep_tokens)

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        collate_fn=trim_batch_collate,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        collate_fn=trim_batch_collate,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
    )

    print(f"Dataset split: {len(train_dataset)} training, {len(val_dataset)} validation samples.")
    return train_loader, val_loader, meta
