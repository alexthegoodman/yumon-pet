//! Yumon Ant: a side-view ant colony where every ant is a pair of WIR networks.
//!
//! The world is a side-view grid (sky above, soil below) that the host grows sideways
//! without bound. Ants walk on surfaces: a cell is walkable when it is open and touches
//! something solid. Five distance fields run with the 4-move `wir path` step over walkable
//! cells: `dn` to the colony's nest chamber, `df` to food an ant can pick up, `dg` to
//! cells next to soil the colony plans to dig, `dm` to the dump on the hill (where dug
//! sand goes) and `dh` to heavy items that need more ants. Every ant runs:
//!
//! - **senses**, a grid program read at its cell: each field graded per heading (-1, 0,
//!   1), blocked headings, which way is less frightening, whether it is at the nest or
//!   the dump, which fields it can smell, what is next to it, the nest distance;
//! - **a brain**, a 0.2 utility program: response curves over its own state (what it
//!   carries, hunger, age, the colony's store) pick one of 4 headings or holding, five
//!   action bits (pick, dig, grip, drop, eat) and an emote, one of 7, which the page
//!   shows as the ant's colour.
//!
//! The host (the page) does the rest: digging plans, gravity, heavy items moving when
//! enough ants grip them, the queen, eggs, hunger and death. `ant_check` runs the
//! networks against the rule as plain code on random inputs; the page runs them against
//! a JavaScript port of the same rule, ant for ant, while the colony lives.

use crate::deep;
use crate::error::{Result, WirError};
use crate::games::{self, PathRule};
use crate::swarm::xorshift;
use crate::tactics::{sparse_layers, stencil_json};

/// Distance field ceiling (4 moves, each step costs 1): ants smell this many steps.
pub const CEILING: i64 = 120;
/// Hunger runs 0..=HUNGER; at HUNGER an ant starves.
pub const HUNGER: i64 = 15;
/// Hunger at which an ant drops everything to eat what it carries.
pub const STARVING: i64 = 12;
/// Hunger at which an ant eats from the store when at the nest.
pub const PECKISH: i64 = 6;
/// Fear painted by the observer: 0..=FEAR.
pub const FEAR: i64 = 3;
/// Colony store as the brain sees it: 0 (empty) ..= 3 (plenty).
pub const STORE: i64 = 3;
/// Beyond this nest distance a free ant heads home.
pub const FAR: i64 = 60;
/// Headings: E N W S, then holding still.
pub const DIR4: [(i64, i64); 4] = [(0, 1), (-1, 0), (0, -1), (1, 0)];
pub const HOLD: usize = 4;
/// Inertia: score for keeping the heading, turning 90 degrees, reversing; holding again.
pub const KEEP: [i64; 3] = [2, 0, -2];
pub const KEEP_HOLD: i64 = 1;

pub const SENSE_CHANNELS: [&str; 10] = ["dn", "df", "dg", "dm", "dh", "walk", "lift", "pull", "dig", "fear"];
const FIELDS: [&str; 5] = ["dn", "df", "dg", "dm", "dh"];
const GRADES: [&str; 5] = ["gn", "gf", "gg", "gm", "gh"];

/// Sense outputs: 5 field grades x 4, b x 4, fg x 4, then the scalars below.
pub const SENSES: usize = 39;
pub const S_B: usize = 20;
pub const S_FG: usize = 24;
pub const S_ZN: usize = 28;
pub const S_ZM: usize = 29;
pub const S_KN: usize = 30;
pub const S_KF: usize = 31;
pub const S_KG: usize = 32;
pub const S_KH: usize = 33;
pub const S_LF: usize = 34;
pub const S_LP: usize = 35;
pub const S_LD: usize = 36;
pub const S_FS: usize = 37;
pub const S_DN: usize = 38;

pub const EMOTES: [&str; 7] = ["calm", "hungry", "working", "carrying", "straining", "scared", "curious"];
pub const ACTIONS: [&str; 5] = ["pick", "dig", "grip", "drop", "eat"];

pub fn path_rule() -> PathRule {
    PathRule { moves: 4, ceiling: CEILING, terrain: 1 }
}

fn sign(v: i64) -> i64 {
    v.signum()
}

/// The senses as plain code. `get(channel, dy, dx)` reads the channels above.
pub fn sense_cell(get: impl Fn(usize, i64, i64) -> i64) -> Vec<i64> {
    let mut s = Vec::with_capacity(SENSES);
    for f in 0..5 {
        for (dy, dx) in DIR4 {
            s.push(sign(get(f, 0, 0) - get(f, dy, dx)));
        }
    }
    for (dy, dx) in DIR4 {
        s.push((get(5, dy, dx) == 0) as i64);
    }
    for (dy, dx) in DIR4 {
        s.push(sign(get(9, 0, 0) - get(9, dy, dx)));
    }
    s.push((get(0, 0, 0) <= 0) as i64);
    s.push((get(3, 0, 0) <= 0) as i64);
    for f in [0, 1, 2, 4] {
        s.push((get(f, 0, 0) < CEILING) as i64);
    }
    for ch in [6, 7, 8] {
        s.push(DIR4.iter().any(|&(dy, dx)| get(ch, dy, dx) == 1) as i64);
    }
    s.push(get(9, 0, 0));
    s.push(get(0, 0, 0));
    s
}

fn tap(ch: &str, dy: i64, dx: i64) -> String {
    if dy == 0 && dx == 0 { ch.to_string() } else { format!("{ch}[{dy}, {dx}]") }
}

/// The sense program: a grid program read at an ant's cell.
pub fn sense_program() -> String {
    let mut src = format!(
        "wir 0.2
# Senses of an ant (generated by `wir ant`). A grid program read at the ant's cell,
# side view (row 0 is the sky). Fields are 4-move distances over walkable cells: dn to
# the nest chamber, df to food one ant can lift, dg to the dig face, dm to the dump on
# the hill, dh to heavy items that need more ants. walk is 1 where an ant can stand
# (ants are small and pass one another), lift / pull / dig mark light items, heavy
# items still short of ants and soil the colony wants dug; fear is painted by the
# observer.
# Headings 0..3 are E N W S.

input dn: grid in [0, {CEILING}] pad {CEILING}
input df: grid in [0, {CEILING}] pad {CEILING}
input dg: grid in [0, {CEILING}] pad {CEILING}
input dm: grid in [0, {CEILING}] pad {CEILING}
input dh: grid in [0, {CEILING}] pad {CEILING}
input walk: grid in [0, 1] pad 0
input lift: grid in [0, 1] pad 0
input pull: grid in [0, 1] pad 0
input dig: grid in [0, 1] pad 0
input fear: grid in [0, {FEAR}] pad 0

# field grades: 1 when the neighbour is nearer the goal, -1 when farther
"
    );
    for (f, g) in FIELDS.iter().zip(GRADES) {
        for (d, (dy, dx)) in DIR4.iter().enumerate() {
            let t = tap(f, *dy, *dx);
            src += &format!("output {g}{d} = gt({f}, {t}) - lt({f}, {t})\n");
        }
    }
    src += "\n# blocked: nowhere to stand\n";
    for (d, (dy, dx)) in DIR4.iter().enumerate() {
        src += &format!("output b{d} = not({})\n", tap("walk", *dy, *dx));
    }
    src += "\n# fear grade: 1 when the neighbour is less frightening\n";
    for (d, (dy, dx)) in DIR4.iter().enumerate() {
        let t = tap("fear", *dy, *dx);
        src += &format!("output fg{d} = gt(fear, {t}) - lt(fear, {t})\n");
    }
    src += "\n# at the nest, at the dump; fields the ant can smell (below the ceiling)\noutput zn = le(dn, 0)\noutput zm = le(dm, 0)\n";
    for (f, k) in [("dn", "kn"), ("df", "kf"), ("dg", "kg"), ("dh", "kh")] {
        src += &format!("output {k} = lt({f}, {CEILING})\n");
    }
    src += "\n# next to a light item, a heavy item short of ants, soil to dig\n";
    for (ch, name) in [("lift", "lf"), ("pull", "lp"), ("dig", "ld")] {
        let t: Vec<String> = DIR4.iter().map(|&(dy, dx)| tap(ch, dy, dx)).collect();
        src += &format!("output {name} = or({})\n", t.join(", "));
    }
    src += "\n# fear here, distance to the nest\noutput fs = fear\noutput dns = dn\n";
    src
}

/// What a brain reads: current option, own state, the colony's store bucket, a wander
/// heading the host turns now and then, and the senses.
#[derive(Debug, Clone, PartialEq)]
pub struct AntIn {
    pub option: usize,
    /// Carrying food, carrying sand, gripping a heavy item (at most one is set by the host).
    pub cf: i64,
    pub cs: i64,
    pub gr: i64,
    pub hunger: i64,
    pub old: i64,
    pub store: i64,
    pub wander: usize,
    /// Role: 0 digger, 1 forager, 2 helper (an individual response threshold).
    pub role: usize,
    pub senses: Vec<i64>,
}

/// The response curves at one state, as plain code.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct Drives {
    pub home: i64,
    pub forage: i64,
    pub dig: i64,
    pub dump: i64,
    pub help: i64,
    pub explore: i64,
    pub flee: i64,
}

impl Drives {
    pub fn all(&self) -> [i64; 7] {
        [self.home, self.forage, self.dig, self.dump, self.help, self.explore, self.flee]
    }
}

/// Upper bounds of each drive (all are >= 0).
pub const DRIVE_MAX: [i64; 7] = [18, 14, 7, 6, 6, 3, 8];
pub const ROLES: [&str; 3] = ["digger", "forager", "helper"];
/// A role adds this to its drive.
pub const ROLE_BONUS: i64 = 3;
/// Each task follows one field: home dn, forage df, dig dg, dump dm, help dh, explore the
/// wander heading, flee the fear grade. A heading on the task's gradient scores this.
pub const PULL: i64 = 4;
pub const TASKS: [&str; 7] = ["home", "forage", "dig", "dump", "help", "explore", "flee"];

/// Bits the brain computes on the way.
struct Bits {
    free: bool,
    hungry: i64,
    starving: bool,
    scared: bool,
    idle: bool,
}

fn bits(x: &AntIn) -> Bits {
    let s = &x.senses;
    let free = x.cf == 0 && x.cs == 0 && x.gr == 0;
    Bits {
        free,
        hungry: (x.hunger - 5).clamp(0, 10),
        starving: x.hunger >= STARVING,
        scared: s[S_FS] >= 1,
        idle: free && s[S_KF] == 0 && s[S_KG] == 0 && s[S_KH] == 0,
    }
}

pub fn drives(x: &AntIn) -> Drives {
    let s = &x.senses;
    let b = bits(x);
    let hs = (x.store >= 1) as i64;
    let fb = (b.free && s[S_KF] == 1) as i64;
    let fb2 = (b.free && s[S_KF] == 1 && x.store < 1) as i64;
    Drives {
        home: (s[S_KN] == 1) as i64 * (6 * x.cf + hs * 2 * b.hungry.min(4) + 4 * (b.free && s[S_DN] >= FAR) as i64),
        forage: fb * (5 - x.store + 2 * x.old + ROLE_BONUS * (x.role == 1) as i64) + fb2 * b.hungry.min(4),
        dig: (b.free && s[S_KG] == 1 && !b.starving) as i64 * (4 - 2 * x.old + ROLE_BONUS * (x.role == 0) as i64),
        dump: 6 * (x.cs == 1 && s[S_KN] == 1) as i64,
        help: (b.free && s[S_KH] == 1 && !b.starving) as i64 * (3 + ROLE_BONUS * (x.role == 2) as i64),
        explore: 3 * (b.idle || s[S_KN] == 0) as i64,
        flee: 8 * b.scared as i64,
    }
}

/// The action bits: pick, dig, grip, drop, eat.
pub fn actions(x: &AntIn) -> [bool; 5] {
    let s = &x.senses;
    let b = bits(x);
    let pick = b.free && s[S_LF] == 1 && !b.scared;
    let dig = b.free && s[S_LD] == 1 && !b.starving && !b.scared;
    let grip = (x.gr == 1 || (b.free && s[S_LP] == 1)) && !b.starving && !b.scared;
    let drop = (x.cf == 1 && s[S_ZN] == 1) || (x.cs == 1 && s[S_ZM] == 1);
    let eat = (s[S_ZN] == 1 && x.store >= 1 && x.hunger >= PECKISH) || (x.cf == 1 && b.starving);
    [pick, dig, grip, drop, eat]
}

fn turn4(a: usize, b: usize) -> usize {
    let t = (a + 4 - b) % 4;
    t.min(4 - t)
}

fn inertia(option: usize, current: usize) -> i64 {
    match (option == HOLD, current == HOLD) {
        (false, false) => KEEP[turn4(option, current)],
        (true, true) => KEEP_HOLD,
        _ => 0,
    }
}

/// Heading scores span at most this either way (drives times grades, plus inertia).
pub fn heading_span() -> i64 {
    PULL + KEEP.iter().map(|k| k.abs()).max().unwrap()
}

/// Holding while working (gripping or acting) scores this: more than any heading.
pub fn hold_bonus() -> i64 {
    heading_span() + 1
}

/// Bounds of every option's score without the blocked term.
pub fn score_range() -> (i64, i64) {
    (-heading_span(), heading_span().max(hold_bonus() + KEEP_HOLD))
}

/// A blocked heading loses more than every score can span, so holding (never blocked)
/// beats it.
pub fn blocked_penalty() -> i64 {
    let (lo, hi) = score_range();
    hi - lo + 1
}

/// Emote intensities: calm, hungry, working, carrying, straining, scared, curious.
pub fn emote_levels(x: &AntIn) -> [i64; 7] {
    let s = &x.senses;
    let b = bits(x);
    let a = actions(x);
    [
        1,
        b.hungry,
        3 * (x.cs == 1 || a[1] || (b.free && s[S_KG] == 1)) as i64,
        4 * x.cf,
        5 * a[2] as i64,
        9 * b.scared as i64,
        2 * (b.idle || s[S_KN] == 0) as i64,
    ]
}

/// The task: the strongest drive (ties to the lower index).
pub fn task(x: &AntIn) -> usize {
    let dv = drives(x).all();
    (0..7).max_by_key(|&f| 7 * dv[f] + (6 - f as i64)).unwrap()
}

/// How heading `d` follows task `t`'s field: -1, 0 or 1.
pub fn task_grade(x: &AntIn, t: usize, d: usize) -> i64 {
    match t {
        0..=4 => x.senses[4 * t + d],
        5 => (x.wander == d) as i64,
        _ => x.senses[S_FG + d],
    }
}

/// Scores of the 5 options (blocked term included), as plain code.
pub fn scores(x: &AntIn) -> [i64; 5] {
    let t = task(x);
    let big = blocked_penalty();
    let a = actions(x);
    let mut out = [0; 5];
    for (d, o) in out.iter_mut().enumerate().take(4) {
        *o = PULL * task_grade(x, t, d) + inertia(d, x.option) - big * x.senses[S_B + d];
    }
    out[HOLD] = hold_bonus() * (x.gr == 1 || a.iter().any(|&b| b)) as i64 + inertia(HOLD, x.option);
    out
}

/// What the brain decides: option, action bits, emote.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Decision {
    pub option: usize,
    pub actions: [bool; 5],
    pub emote: usize,
}

/// The brain as plain code. Ties go to the lower index.
pub fn brain_rule(x: &AntIn) -> Decision {
    let sc = scores(x);
    let option = (0..5).max_by_key(|&d| 5 * sc[d] + (4 - d as i64)).unwrap();
    let em = emote_levels(x);
    let emote = (0..7).max_by_key(|&e| 7 * em[e] + (6 - e as i64)).unwrap();
    Decision { option, actions: actions(x), emote }
}

fn term(k: i64, x: &str) -> String {
    match k {
        0 => String::new(),
        1 => format!(" + {x}"),
        -1 => format!(" - {x}"),
        k if k < 0 => format!(" - {}*{x}", -k),
        k => format!(" + {k}*{x}"),
    }
}

fn signed(v: i64) -> String {
    if v < 0 { format!("- {}", -v) } else { format!("+ {v}") }
}

fn sum_text(terms: &str) -> String {
    match terms.strip_prefix(" - ") {
        Some(rest) => format!("-{rest}"),
        None if terms.is_empty() => "0".to_string(),
        None => terms.trim_start_matches(" + ").to_string(),
    }
}

/// One-hot argmax of `keys` (never equal) as outputs `{name}0..`.
fn argmax_text(prefix: &str, name: &str, n: usize) -> String {
    let mut src = String::new();
    for d in 0..n {
        for e in d + 1..n {
            src += &format!("let {prefix}w{d}_{e} = gt({prefix}key{d}, {prefix}key{e})\n");
        }
    }
    for d in 0..n {
        let parts: Vec<String> =
            (0..n).filter(|&e| e != d).map(|e| if e > d { format!("{prefix}w{d}_{e}") } else { format!("not({prefix}w{e}_{d})") }).collect();
        src += &format!("output {name}{d} = and({})\n", parts.join(", "));
    }
    src
}

/// The brain program: response curves, actions, scores for 4 headings and holding, the
/// best option one-hot, and the emote one-hot.
pub fn brain_program() -> String {
    let list = |p: &str, n: usize| (0..n).map(|k| format!("{p}{k}")).collect::<Vec<_>>().join(", ");
    let grades: Vec<String> = GRADES.iter().map(|g| list(g, 4)).collect();
    let big = blocked_penalty();
    let mut src = format!(
        "wir 0.2
# Brain of an ant (generated by `wir ant`): response curves over its own state, five
# action bits, a score for each heading (0..3: E N W S) and for holding (4), the best
# option one-hot, and an emote one-hot (calm hungry working carrying straining scared
# curious) that the page shows as the ant's colour. o is the current option, w the
# wander heading the host turns now and then; the senses come from the sense program.

input {o}: R1 in [0, 1]
input cf: R1 in [0, 1]
input cs: R1 in [0, 1]
input gr: R1 in [0, 1]
input hunger: R1 in [0, {HUNGER}]
input old: R1 in [0, 1]
input store: R1 in [0, {STORE}]
input {w}: R1 in [0, 1]
input r0, r1, r2: R1 in [0, 1]
input {g}: R1 in [-1, 1]
input {b}: R1 in [0, 1]
input {fg}: R1 in [-1, 1]
input zn, zm, kn, kf, kg, kh, lf, lp, ld: R1 in [0, 1]
input fs: R1 in [0, {FEAR}]
input dns: R1 in [0, {CEILING}]

# --- state ---
let free = and(not(cf), not(cs), not(gr))
let hungry = clip(hunger - 5, 0, 10)
let starving = ge(hunger, {STARVING})
let scared = ge(fs, 1)
let hs = ge(store, 1)
let idle = and(free, not(kf), not(kg), not(kh))

# --- response curves ---
# home: bring food back; go eat when hungry and the store has food; come back from afar
let home = select(kn, 6*cf + select(hs, 2*min(hungry, 4), 0) + 4*and(free, ge(dns, {FAR})), 0)
# roles r0 r1 r2 (digger, forager, helper) are individual thresholds: each adds {rb} to its drive
# forage: more when the store is low, old ants forage more; hungrier if the store is empty
let fb = and(free, kf)
let fb2 = and(free, kf, not(hs))
let forage = select(fb, 5 - store + 2*old + {rb}*r1, 0) + select(fb2, min(hungry, 4), 0)
# dig: young ants dig more; nobody digs while starving
let dig = select(and(free, kg, not(starving)), 4 - 2*old + {rb}*r0, 0)
let dump = 6*and(cs, kn)
let help = select(and(free, kh, not(starving)), 3 + {rb}*r2, 0)
let lost = or(idle, not(kn))
let explore = 3*lost
let flee = 8*scared

# --- actions ---
output pick = and(free, lf, not(scared))
output dig2 = and(free, ld, not(starving), not(scared))
output grip = and(or(gr, and(free, lp)), not(starving), not(scared))
output drop = or(and(cf, zn), and(cs, zm))
output eat = or(and(zn, hs, ge(hunger, {PECKISH})), and(cf, starving))
let work = or(gr, pick, dig2, grip, drop, eat)
# what the emote keys read, named so `wir superpose-choice-layer` can take them as features
let workem = or(cs, dig2, and(free, kg))
let carrying = cf

# --- task: the strongest drive (ties to the lower index) ---
",
        o = list("o", 5),
        w = list("w", 4),
        g = grades.join(", "),
        b = list("b", 4),
        fg = list("fg", 4),
        rb = ROLE_BONUS,
    );
    let drives = ["home", "forage", "dig", "dump", "help", "explore", "flee"];
    for (f, n) in drives.iter().enumerate() {
        src += &format!("let tkey{f} = 7*{n} + {}\n", 6 - f);
    }
    src += &argmax_text("t", "task", 7).replace("output task", "let task");
    src += &format!(
        "\n# --- scores: {PULL} along the task's field (grades are -1, 0 or 1, so task * grade is an
# exact product). Inertia and a blocked heading losing {big} are packed into one unit. ---\n"
    );
    for d in 0..5 {
        let mut l = String::new();
        for k in 0..5 {
            l += &term(inertia(d, k), &format!("o{k}"));
        }
        if d < 4 {
            l += &term(-big, &format!("b{d}"));
        }
        let l = sum_text(&l);
        let floor = if d < 4 { KEEP.iter().min().unwrap().min(&0) - big } else { 0 };
        if floor == 0 {
            src += &format!("let k{d} = relu({l})\n");
        } else {
            src += &format!("let k{d} = relu({l} {}) {}\n", signed(-floor), signed(floor));
        }
    }
    src += "\n";
    for d in 0..4 {
        let follow: Vec<String> = GRADES
            .iter()
            .enumerate()
            .map(|(f, g)| format!("task{f}*{g}{d}"))
            .chain([format!("task5*w{d}"), format!("task6*fg{d}")])
            .collect();
        src += &format!("let s{d} = {PULL}*({}) + k{d}\n", follow.join(" + "));
    }
    src += &format!("let s4 = {}*work + k4\n", hold_bonus());
    let lo = score_range().0 - big;
    src += &format!("\n# key: the score as one unit (scores are at least {lo}), times 5 plus a tie-break\n");
    for d in 0..5 {
        src += &format!("let key{d} = 5*relu(s{d} {}) {}\n", signed(-lo), signed(5 * lo + 4 - d as i64));
    }
    src += "\n# the best option beats every other key\n";
    src += &argmax_text("", "o2_", 5);
    src += "\n# --- emote: the strongest feeling (ties to the lower index) ---\n";
    let levels = [
        "1".to_string(),
        "hungry".to_string(),
        "3*workem".to_string(),
        "4*carrying".to_string(),
        "5*grip".to_string(),
        "9*scared".to_string(),
        "2*lost".to_string(),
    ];
    for (e, l) in levels.iter().enumerate() {
        src += &format!("let ekey{e} = 7*({l}) + {}\n", 6 - e);
    }
    src += &argmax_text("e", "em", 7);
    src
}

/// The compiled path, sense and brain networks.
pub struct AntNets {
    pub path: deep::StencilWeights,
    pub sense: deep::StencilWeights,
    pub brain: deep::DeepWeights,
    path_net: deep::SparseNet,
    sense_net: deep::SparseNet,
    brain_net: deep::SparseNet,
}

impl AntNets {
    pub fn compile() -> Result<Self> {
        let pc = deep::compile(&games::path_program(&path_rule())?, 1e-6)?;
        let path = deep::StencilWeights::from_compiled(&pc).ok_or_else(|| WirError::new("path is not a grid program"))?;
        let sc = deep::compile(&sense_program(), 1e-6)?;
        let sense = deep::StencilWeights::from_compiled(&sc).ok_or_else(|| WirError::new("sense is not a grid program"))?;
        let brain = deep::compile(&brain_program(), 1e-6)?.weights;
        Ok(Self {
            path_net: deep::SparseNet::new(&path.net),
            sense_net: deep::SparseNet::new(&sense.net),
            brain_net: deep::SparseNet::new(&brain),
            path,
            sense,
            brain,
        })
    }

    pub fn path_cell(&mut self, get: impl Fn(usize, i64, i64) -> i64) -> i64 {
        let x: Vec<f64> = self.path.taps.iter().map(|&(ch, dy, dx)| get(ch, dy, dx) as f64).collect();
        self.path_net.eval(&x)[0].round() as i64
    }

    pub fn senses(&mut self, get: impl Fn(usize, i64, i64) -> i64) -> Vec<i64> {
        let x: Vec<f64> = self.sense.taps.iter().map(|&(ch, dy, dx)| get(ch, dy, dx) as f64).collect();
        self.sense_net.eval(&x).iter().map(|v| v.round() as i64).collect()
    }

    /// Brain input vector in program order.
    pub fn brain_inputs(x: &AntIn) -> Vec<f64> {
        let mut v: Vec<f64> = (0..5).map(|k| (k == x.option) as i64 as f64).collect();
        v.extend([x.cf, x.cs, x.gr, x.hunger, x.old, x.store].map(|k| k as f64));
        v.extend((0..4).map(|k| (k == x.wander) as i64 as f64));
        v.extend((0..3).map(|k| (k == x.role) as i64 as f64));
        v.extend(x.senses.iter().map(|&k| k as f64));
        v
    }

    /// The decision from the network, or None when its outputs are not clean bits.
    pub fn decide(&mut self, x: &AntIn) -> Option<Decision> {
        let out = self.brain_net.eval(&Self::brain_inputs(x)).to_vec();
        let bit = |v: f64| if v.abs() < 1e-6 { Some(false) } else if (v - 1.0).abs() < 1e-6 { Some(true) } else { None };
        let named = |n: &str| -> Option<bool> { bit(out[self.brain.outputs.iter().position(|o| o == n)?]) };
        let one = |prefix: &str, n: usize| -> Option<usize> {
            let bits: Vec<bool> = (0..n).map(|k| named(&format!("{prefix}{k}"))).collect::<Option<_>>()?;
            let hot: Vec<usize> = (0..n).filter(|&k| bits[k]).collect();
            (hot.len() == 1).then(|| hot[0])
        };
        Some(Decision {
            option: one("o2_", 5)?,
            actions: [named("pick")?, named("dig2")?, named("grip")?, named("drop")?, named("eat")?],
            emote: one("em", 7)?,
        })
    }
}

/// Random brain input over the declared domain, weighted toward interesting states.
pub fn random_ant_in(rng: &mut u64) -> AntIn {
    let mut s = Vec::with_capacity(SENSES);
    for _ in 0..20 {
        s.push(xorshift(rng, 3) as i64 - 1);
    }
    let all_blocked = xorshift(rng, 16) == 0;
    for _ in 0..4 {
        s.push((all_blocked || xorshift(rng, 4) == 0) as i64);
    }
    let calm = xorshift(rng, 2) == 0;
    for _ in 0..4 {
        s.push(if calm { 0 } else { xorshift(rng, 3) as i64 - 1 });
    }
    for _ in S_ZN..S_FS {
        s.push(xorshift(rng, 2) as i64);
    }
    s.push(if calm { 0 } else { xorshift(rng, FEAR as u64 + 1) as i64 });
    s.push(xorshift(rng, CEILING as u64 + 1) as i64);
    let carry = xorshift(rng, 5);
    AntIn {
        option: xorshift(rng, 5) as usize,
        cf: (carry == 1) as i64,
        cs: (carry == 2) as i64,
        gr: (carry == 3) as i64,
        hunger: xorshift(rng, HUNGER as u64 + 1) as i64,
        old: xorshift(rng, 2) as i64,
        store: xorshift(rng, STORE as u64 + 1) as i64,
        wander: xorshift(rng, 4) as usize,
        role: xorshift(rng, 3) as usize,
        senses: s,
    }
}

/// Random sense window: per tap a value in its channel's range (fields mostly near one
/// another, so every grade shows up).
fn random_taps(taps: &[(usize, i64, i64)], rng: &mut u64) -> std::collections::HashMap<(usize, i64, i64), i64> {
    let mut vals = std::collections::HashMap::new();
    let base: Vec<i64> = (0..5).map(|_| xorshift(rng, CEILING as u64 + 1) as i64).collect();
    for &(ch, dy, dx) in taps {
        let v = match ch {
            0..=4 if xorshift(rng, 5) != 0 => (base[ch] + xorshift(rng, 3) as i64 - 1).clamp(0, CEILING),
            0..=4 => xorshift(rng, CEILING as u64 + 1) as i64,
            9 => xorshift(rng, FEAR as u64 + 1) as i64,
            5 => (xorshift(rng, 4) != 0) as i64,
            _ => (xorshift(rng, 5) == 0) as i64,
        };
        vals.insert((ch, dy, dx), v);
    }
    vals
}

#[derive(Debug, Clone, PartialEq)]
pub struct AntCheck {
    pub cases: u64,
    pub path_mismatches: u64,
    pub sense_mismatches: u64,
    pub brain_mismatches: u64,
    /// Decisions that picked a blocked heading.
    pub blocked_picks: u64,
    /// How often each option and emote was picked (rule), for coverage.
    pub options: [u64; 5],
    pub emotes: [u64; 7],
    pub path_shape: (usize, Vec<usize>, usize),
    pub sense_shape: (usize, Vec<usize>, usize),
    pub brain_shape: (Vec<usize>, usize),
}

/// The path, sense and brain networks against the rule on `cases` random inputs each.
pub fn ant_check(cases: u64, seed: u64) -> Result<AntCheck> {
    let mut nets = AntNets::compile()?;
    let mut rng = seed.max(1);
    let g = path_rule();
    let mut path_mismatches = 0;
    for _ in 0..cases {
        let base = xorshift(&mut rng, CEILING as u64 + 1) as i64;
        let mut vals = std::collections::HashMap::new();
        for &(ch, dy, dx) in &nets.path.taps.clone() {
            let v = match ch {
                0 => (base + xorshift(&mut rng, 5) as i64 - 2).clamp(0, CEILING),
                _ => (xorshift(&mut rng, 4) == 0) as i64,
            };
            vals.insert((ch, dy, dx), v);
        }
        let get = |ch: usize, dy: i64, dx: i64| vals[&(ch, dy, dx)];
        path_mismatches += (nets.path_cell(get) != games::path_cell(&g, get)) as u64;
    }
    let mut sense_mismatches = 0;
    let taps = nets.sense.taps.clone();
    for _ in 0..cases {
        let vals = random_taps(&taps, &mut rng);
        let get = |ch: usize, dy: i64, dx: i64| -> i64 {
            *vals.get(&(ch, dy, dx)).unwrap_or_else(|| panic!("the rule reads channel {ch} at [{dy}, {dx}], which the program does not"))
        };
        sense_mismatches += (nets.senses(get) != sense_cell(get)) as u64;
    }
    let (mut brain_mismatches, mut blocked_picks) = (0, 0);
    let (mut options, mut emotes) = ([0; 5], [0; 7]);
    for _ in 0..cases {
        let x = random_ant_in(&mut rng);
        let want = brain_rule(&x);
        brain_mismatches += (nets.decide(&x) != Some(want)) as u64;
        blocked_picks += (want.option < 4 && x.senses[S_B + want.option] == 1) as u64;
        options[want.option] += 1;
        emotes[want.emote] += 1;
    }
    Ok(AntCheck {
        cases,
        path_mismatches,
        sense_mismatches,
        brain_mismatches,
        blocked_picks,
        options,
        emotes,
        path_shape: (nets.path.taps.len(), nets.path.net.hidden(), nets.path.param_count()),
        sense_shape: (nets.sense.taps.len(), nets.sense.net.hidden(), nets.sense.param_count()),
        brain_shape: (nets.brain.hidden(), nets.brain.param_count()),
    })
}

/// Everything the page needs: the three networks (sparse layers, taps, sources), the
/// constants, and test vectors (inputs with the rule's outputs) so the page can check
/// its JavaScript port of the rule before using it as the live reference.
/// `variants`: extra brains for the page's brain selector, `(label, wir source)` (see
/// `superpose::variants_json`).
pub fn export_json(vectors: u64, seed: u64, variants: &[(String, String)]) -> Result<String> {
    let nets = AntNets::compile()?;
    let mut rng = seed.max(1);
    let mut sense_vectors = Vec::new();
    for _ in 0..vectors {
        let vals = random_taps(&nets.sense.taps, &mut rng);
        let x: Vec<i64> = nets.sense.taps.iter().map(|t| vals[t]).collect();
        let y = sense_cell(|ch, dy, dx| vals[&(ch, dy, dx)]);
        sense_vectors.push(serde_json::json!([x, y]));
    }
    let mut brain_vectors = Vec::new();
    for _ in 0..vectors {
        let x = random_ant_in(&mut rng);
        let d = brain_rule(&x);
        let input: Vec<i64> = AntNets::brain_inputs(&x).iter().map(|&v| v as i64).collect();
        brain_vectors.push(serde_json::json!([input, d.option, d.actions, d.emote]));
    }
    let v = serde_json::json!({
        "format": "wir-ant-demo",
        "consts": {
            "ceiling": CEILING, "hunger": HUNGER, "starving": STARVING, "peckish": PECKISH,
            "fear": FEAR, "store": STORE, "far": FAR, "keep": KEEP, "keep_hold": KEEP_HOLD,
            "big": blocked_penalty(), "hold_bonus": hold_bonus(), "pull": PULL, "tasks": TASKS, "roles": ROLES, "role_bonus": ROLE_BONUS,
            "emotes": EMOTES, "actions": ACTIONS,
        },
        "path": stencil_json(&nets.path, &games::path_program(&path_rule())?),
        "sense": stencil_json(&nets.sense, &sense_program()),
        "brain": {
            "inputs": nets.brain.inputs, "outputs": nets.brain.outputs,
            "hidden": nets.brain.hidden(), "params": nets.brain.param_count(),
            "layers": sparse_layers(&nets.brain),
            "source": brain_program(),
        },
        "brains": crate::superpose::variants_json(variants, &nets.brain.inputs, &nets.brain.outputs)?,
        "vectors": { "sense": sense_vectors, "brain": brain_vectors },
    });
    Ok(serde_json::to_string(&v).unwrap())
}
