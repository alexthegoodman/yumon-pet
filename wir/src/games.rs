//! Generated 0.2 programs with reference simulators: checkable training data.
//!
//! `pong_program` writes one Pong step for a set of parameters, `pong_step` is the
//! same step as ordinary branching code, and `pong_check` compiles the program and
//! compares the network against the simulator on every state (or a random sample of
//! them when there are too many).
//!
//! `path_program` writes one value-iteration step for grid pathfinding as a grid
//! (stencil) program; `path_cell` / `path_step` are the rule as plain code,
//! `path_distances` is Dijkstra, and `path_check` compares the compiled cell network
//! with the rule on every cell input (or a sample) and whole random grids with both.

use crate::deep;
use crate::error::{Result, WirError};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pong {
    /// Columns, paddles included (the ball uses 1..width-2).
    pub width: i64,
    /// Rows.
    pub height: i64,
    /// Rows a paddle covers.
    pub paddle: i64,
    /// Ball speed per axis: velocities are -speed or +speed.
    pub speed: i64,
    /// Rows a paddle moves per step.
    pub paddle_speed: i64,
}

impl Default for Pong {
    fn default() -> Self {
        Self { width: 16, height: 12, paddle: 3, speed: 1, paddle_speed: 1 }
    }
}

pub const PONG_INPUTS: [&str; 8] = ["bx", "by", "vx", "vy", "pl", "pr", "ul", "ur"];
pub const PONG_OUTPUTS: [&str; 8] = ["pl2", "pr2", "bx2", "by2", "vx2", "vy2", "point_l", "point_r"];

impl Pong {
    pub fn validate(&self) -> Result<()> {
        let Pong { width: w, height: h, paddle: p, speed: s, paddle_speed: m } = *self;
        let ok = w >= 5 && h >= 2 && (1..h).contains(&p) && s >= 1 && s <= h - 1 && s <= w - 3 && m >= 1 && m <= h - p;
        if ok {
            Ok(())
        } else {
            Err(WirError::new(format!(
                "pong needs width >= 5, height >= 2, 1 <= paddle < height, 1 <= speed <= min(height - 1, width - 3) and 1 <= paddle speed <= height - paddle (got {self:?})"
            )))
        }
    }

    /// File-name friendly tag.
    pub fn tag(&self) -> String {
        format!("pong_w{}_h{}_p{}_s{}_m{}", self.width, self.height, self.paddle, self.speed, self.paddle_speed)
    }

    fn top(&self) -> i64 {
        self.height - self.paddle
    }
}

/// One step: [bx, by, vx, vy, pl, pr, ul, ur] -> [pl2, pr2, bx2, by2, vx2, vy2, point_l, point_r].
pub fn pong_step(g: &Pong, s: [i64; 8]) -> [i64; 8] {
    let [bx, by, vx, vy, pl, pr, ul, ur] = s;
    let (last_col, last_row) = (g.width - 2, g.height - 1);
    let pl2 = (pl + g.paddle_speed * ul).clamp(0, g.top());
    let pr2 = (pr + g.paddle_speed * ur).clamp(0, g.top());
    let ny = by + vy;
    let (y, vy2) = if ny < 0 {
        (-ny, -vy)
    } else if ny > last_row {
        (2 * last_row - ny, -vy)
    } else {
        (ny, vy)
    };
    let nx = bx + vx;
    let (mut bx2, mut by2, mut vx2, mut point_l, mut point_r) = (nx, y, vx, 0, 0);
    if nx < 1 || nx > last_col {
        let (paddle, reflected) = if nx < 1 { (pl2, 2 - nx) } else { (pr2, 2 * last_col - nx) };
        vx2 = -vx;
        if paddle <= y && y < paddle + g.paddle {
            bx2 = reflected;
        } else {
            (bx2, by2) = (g.width / 2, g.height / 2);
            if nx < 1 {
                point_r = 1;
            } else {
                point_l = 1;
            }
        }
    }
    [pl2, pr2, bx2, by2, vx2, vy2, point_l, point_r]
}

/// Number of states in the program's domain.
pub fn pong_state_count(g: &Pong) -> u64 {
    let (w, h, t) = ((g.width - 2) as u64, g.height as u64, (g.top() + 1) as u64);
    w * h * 4 * t * t * 9
}

/// The state with this index (mixed radix over the domain).
pub fn pong_state(g: &Pong, mut i: u64) -> [i64; 8] {
    let mut digit = |n: i64| {
        let d = (i % n as u64) as i64;
        i /= n as u64;
        d
    };
    let bx = 1 + digit(g.width - 2);
    let by = digit(g.height);
    let vx = if digit(2) == 0 { -g.speed } else { g.speed };
    let vy = if digit(2) == 0 { -g.speed } else { g.speed };
    let pl = digit(g.top() + 1);
    let pr = digit(g.top() + 1);
    let ul = digit(3) - 1;
    let ur = digit(3) - 1;
    [bx, by, vx, vy, pl, pr, ul, ur]
}

fn signed(k: i64, name: &str) -> String {
    if k == 1 { name.to_string() } else { format!("{k}*{name}") }
}

/// The 0.2 source of one Pong step, with asserts taken from `pong_step`.
pub fn pong_program(g: &Pong) -> Result<String> {
    g.validate()?;
    let Pong { width: w, height: h, paddle: p, speed: s, paddle_speed: m } = *g;
    let (last_col, last_row, top) = (w - 2, h - 1, g.top());
    let rows = if p == 1 { "row p".to_string() } else { format!("rows p..p+{}", p - 1) };
    let mut src = format!(
        "wir 0.2
# One Pong step on an integer grid ({tag}, generated by `wir pong`).
# Field {w} x {h}: paddles live in columns 0 and {right}, the ball in columns 1..{last_col}
# and rows 0..{last_row}. A paddle at p covers {rows}. Ball velocities are -{s} or +{s},
# controls -1, 0 or +1. Every value is an integer, so every comparison is exact.

input bx: R1 in [1, {last_col}]
input by: R1 in [0, {last_row}]
input vx, vy: R1 in [-{s}, {s}]
input pl, pr: R1 in [0, {top}]
input ul, ur: R1 in [-1, 1]

# paddles move {m} row(s) per step and stop at the walls
output pl2 = clip(pl + {ul}, 0, {top})
output pr2 = clip(pr + {ur}, 0, {top})

# the ball bounces off the top and bottom walls
let ny = by + vy
let wall_lo = lt(ny, 0)
let wall_hi = gt(ny, {last_row})
let y = ny + 2*relu(-ny) - 2*relu(ny - {last_row})

# reaching a paddle column: a hit reflects, a miss scores
let nx = bx + vx
let at_l = lt(nx, 1)
let at_r = gt(nx, {last_col})
let hit_l = and(at_l, ge(y, pl2), le(y, pl2 + {span}))
let hit_r = and(at_r, ge(y, pr2), le(y, pr2 + {span}))
let miss = at_l + at_r - hit_l - hit_r
let x = nx + 2*relu(1 - nx) - 2*relu(nx - {last_col})

# after a miss the ball restarts in the middle, heading back the way it came from
output bx2 = select(miss, {cx}, x)
output by2 = select(miss, {cy}, y)
output vx2 = vx + {twice}*at_l - {twice}*at_r
output vy2 = vy + {twice}*wall_lo - {twice}*wall_hi
output point_l = at_r - hit_r
output point_r = at_l - hit_l

# inputs in order: bx, by, vx, vy, pl, pr, ul, ur
",
        tag = g.tag(),
        right = w - 1,
        ul = signed(m, "ul"),
        ur = signed(m, "ur"),
        span = p - 1,
        cx = w / 2,
        cy = h / 2,
        twice = 2 * s,
    );
    // Asserts: a free move, a wall bounce, a left hit and a left miss.
    let (cx, cy) = (w / 2, h / 2);
    let row_after = |by: i64, vy: i64| pong_step(g, [cx, by, s, vy, 0, 0, 0, 0])[3];
    let y_hit = row_after(cy, s);
    let pl_hit = (y_hit - (p - 1) / 2).clamp(0, top);
    let pl_miss = if y_hit >= p { 0 } else { top };
    let cases = [
        [cx, cy, s, s, 0, top, 0, 0],
        [cx, 0, s, -s, top, 0, 1, -1],
        [1, cy, -s, s, pl_hit, 0, 0, 0],
        [1, cy, -s, s, pl_miss, 0, 0, 0],
    ];
    for c in cases {
        let y = pong_step(g, c);
        let args = c.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(", ");
        let checks: Vec<String> = [2, 3, 4, 5, 7].iter().map(|&k| format!("{}({args}) == {}", PONG_OUTPUTS[k], y[k])).collect();
        src.push_str(&format!("assert {}\n", checks.join(", ")));
    }
    Ok(src)
}

/// Outcome of checking a compiled program against the simulator.
#[derive(Debug, Clone, PartialEq)]
pub struct PongCheck {
    pub states: u64,
    pub exhaustive: bool,
    pub mismatches: u64,
    pub worst: f64,
    pub hidden: Vec<usize>,
    pub params: usize,
}

/// Compile `src` and compare it with `pong_step` on every state, or on `limit` random
/// states (seeded) when the domain is larger than `limit`.
pub fn pong_check(g: &Pong, src: &str, limit: u64, seed: u64) -> Result<PongCheck> {
    let c = deep::compile(src, 1e-6)?;
    let total = pong_state_count(g);
    let exhaustive = total <= limit;
    let mut rng = seed.max(1);
    let (mut mismatches, mut worst) = (0, 0.0f64);
    let n = if exhaustive { total } else { limit };
    for i in 0..n {
        let k = if exhaustive {
            i
        } else {
            rng ^= rng << 13;
            rng ^= rng >> 7;
            rng ^= rng << 17;
            rng % total
        };
        let s = pong_state(g, k);
        let want = pong_step(g, s);
        let got = c.weights.eval(&s.map(|v| v as f64));
        let d = got.iter().zip(want).map(|(a, b)| (a - b as f64).abs()).fold(0.0, f64::max);
        worst = worst.max(d);
        mismatches += (d > 1e-6) as u64;
    }
    Ok(PongCheck { states: n, exhaustive, mismatches, worst, hidden: c.weights.hidden(), params: c.weights.param_count() })
}

