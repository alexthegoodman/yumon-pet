//! Cellular water as a grid (stencil) program, with a reference simulator.
//!
//! `fluid_program` writes one step: gravity pours water into the cell below, then
//! cells trade in alternating left/right pairs and the higher one gives half the
//! difference. The program ends with `conserve m2 = m`, which the compiler proves
//! (total water never changes on any grid). `fluid_cell` / `fluid_step` are the rule as
//! plain code, and `fluid_check` compares the compiled cell network with the rule on
//! cell inputs and on whole random grids run for many steps.

use crate::deep;
use crate::error::{Result, WirError};

/// One step of cellular water. Each cell holds 0 to `capacity` units; walls hold none.
/// Gravity first: a cell pours as much as fits into the cell below. Then levelling:
/// cells trade in pairs (the `pair` channel is 1 where a cell trades with its
/// right-hand neighbour this step and flips every step, so the pairing alternates),
/// and the higher cell of a pair gives half the difference, rounded up.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FluidRule {
    /// Units in a full cell (even).
    pub capacity: i64,
}

impl Default for FluidRule {
    fn default() -> Self {
        Self { capacity: 16 }
    }
}

/// Channels of a fluid grid, in program order.
pub const FLUID_CHANNELS: [&str; 3] = ["m", "wall", "pair"];

impl FluidRule {
    pub fn validate(&self) -> Result<()> {
        if (2..=1000).contains(&self.capacity) && self.capacity % 2 == 0 {
            Ok(())
        } else {
            Err(WirError::new(format!("fluid needs an even capacity in 2..1000 (got {})", self.capacity)))
        }
    }

    pub fn tag(&self) -> String {
        format!("fluid_c{}", self.capacity)
    }

    /// Value outside the grid for each channel: no water, wall, no pairing.
    pub fn pads(&self) -> [i64; 3] {
        [0, 1, 0]
    }

    /// Integer range of each channel.
    pub fn span(&self, ch: usize) -> (i64, i64) {
        if ch == 0 { (0, self.capacity) } else { (0, 1) }
    }
}

/// Half of d rounded away from zero, saturating at capacity / 2 (the program's `half`).
pub fn fluid_half(g: &FluidRule, d: i64) -> i64 {
    d.signum() * ((d.abs() + 1) / 2).min(g.capacity / 2)
}

/// The rule for one cell as plain code: (m2, pair2). `get(channel, dy, dx)` reads the
/// grid around the cell (pads outside it).
pub fn fluid_cell(g: &FluidRule, get: impl Fn(usize, i64, i64) -> i64) -> (i64, i64) {
    let c = g.capacity;
    let fall = |dy: i64, dx: i64| get(0, dy, dx).min((c - get(0, dy + 1, dx) - c * get(1, dy + 1, dx)).max(0));
    let mv = |dx: i64| get(0, 0, dx) - fall(0, dx) + fall(-1, dx);
    let flow = |dx: i64| {
        let open = get(2, 0, dx) == 1 && get(1, 0, dx) == 0 && get(1, 0, dx + 1) == 0;
        if open { fluid_half(g, mv(dx) - mv(dx + 1)) } else { 0 }
    };
    (mv(0) - flow(0) + flow(-1), 1 - get(2, 0, 0))
}

/// A fluid grid: row-major water, walls and pairing.
#[derive(Debug, Clone, PartialEq)]
pub struct FluidGrid {
    pub h: usize,
    pub w: usize,
    pub fields: [Vec<i64>; 3],
}

impl FluidGrid {
    /// Empty and open, pairing by alternating columns.
    pub fn new(h: usize, w: usize) -> Self {
        let pair = (0..h * w).map(|i| (i % w % 2 == 0) as i64).collect();
        Self { h, w, fields: [vec![0; h * w], vec![0; h * w], pair] }
    }

    pub fn mass(&self) -> i64 {
        self.fields[0].iter().sum()
    }

    pub fn inputs(&self) -> Vec<Vec<f64>> {
        self.fields.iter().map(|f| f.iter().map(|&v| v as f64).collect()).collect()
    }
}

/// One step of the reference simulator: the new water and pairing fields.
pub fn fluid_step(g: &FluidRule, s: &FluidGrid) -> [Vec<i64>; 2] {
    let pads = g.pads();
    let (h, w) = (s.h as i64, s.w as i64);
    let mut out = [Vec::with_capacity(s.h * s.w), Vec::with_capacity(s.h * s.w)];
    for r in 0..h {
        for c in 0..w {
            let (m2, p2) = fluid_cell(g, |ch, dy, dx| {
                let (y, x) = (r + dy, c + dx);
                if y < 0 || x < 0 || y >= h || x >= w { pads[ch] } else { s.fields[ch][(y * w + x) as usize] }
            });
            out[0].push(m2);
            out[1].push(p2);
        }
    }
    out
}

/// The stencil source of one step.
pub fn fluid_program(g: &FluidRule) -> Result<String> {
    g.validate()?;
    let c = g.capacity;
    let pos: Vec<String> = (1..=c / 2).map(|j| format!("ge(d, {})", 2 * j - 1)).collect();
    let neg: Vec<String> = (1..=c / 2).map(|j| format!("le(d, {})", -(2 * j - 1))).collect();
    Ok(format!(
        "wir 0.2
# One step of cellular water ({tag}, generated by `wir fluid`).
# The program is one cell's rule; the compiler runs it at every cell (a convolution).
# m is water in units, 0 to {c} (a full cell); walls hold none. pair is 1 where the
# cell trades with its right-hand neighbour this step and 0 where it trades with its
# left; start it as alternating columns, the step flips it.
# Outside the grid, m reads 0 and wall reads 1.

input m: grid in [0, {c}] pad 0
input wall: grid in [0, 1] pad 1
input pair: grid in [0, 1] pad 0

# gravity: pour as much as fits into the cell below (nothing fits into a wall)
let fall = min(m, relu({c} - m[1, 0] - {c}*wall[1, 0]))
let mv = m - fall + fall[-1, 0]

# levelling: the higher cell of a pair gives half the difference, rounded up
let d = mv - mv[0, 1]
let half = {pos} - {neg}
let flow = select(and(pair, not(wall), not(wall[0, 1])), half, 0)

# what flows out of one cell flows into its neighbour
output m2 = mv - flow + flow[0, -1]
output pair2 = not(pair)
conserve m2 = m
",
        tag = g.tag(),
        pos = pos.join(" + "),
        neg = neg.join(" - "),
    ))
}

fn xorshift(rng: &mut u64, n: u64) -> u64 {
    *rng ^= *rng << 13;
    *rng ^= *rng >> 7;
    *rng ^= *rng << 17;
    *rng % n.max(1)
}

/// Random grids for checks: sometimes a walled box, random ledges and pillars, water
/// poured in random blocks or (a third of the time) random water in every open cell.
pub fn fluid_random_grid(g: &FluidRule, h: usize, w: usize, rng: &mut u64) -> FluidGrid {
    let mut s = FluidGrid::new(h, w);
    let at = |r: usize, c: usize| r * w + c;
    if xorshift(rng, 2) == 0 {
        for r in 0..h {
            for c in 0..w {
                if r + 1 == h || c == 0 || c + 1 == w {
                    s.fields[1][at(r, c)] = 1;
                }
            }
        }
    }
    for _ in 0..xorshift(rng, 1 + (h * w / 24) as u64) {
        let (r, c) = (xorshift(rng, h as u64) as usize, xorshift(rng, w as u64) as usize);
        let len = 1 + xorshift(rng, w as u64 / 2) as usize;
        let vertical = xorshift(rng, 3) == 0;
        for k in 0..len {
            let (y, x) = if vertical { (r + k, c) } else { (r, c + k) };
            if y < h && x < w {
                s.fields[1][at(y, x)] = 1;
            }
        }
    }
    let scattered = xorshift(rng, 3) == 0;
    for _ in 0..1 + xorshift(rng, 4) {
        let (r, c) = (xorshift(rng, h as u64) as usize, xorshift(rng, w as u64) as usize);
        let (bh, bw) = (1 + xorshift(rng, h as u64 / 2) as usize, 1 + xorshift(rng, w as u64 / 2) as usize);
        for y in r..(r + bh).min(h) {
            for x in c..(c + bw).min(w) {
                s.fields[0][at(y, x)] = g.capacity;
            }
        }
    }
    for i in 0..h * w {
        if scattered {
            s.fields[0][i] = xorshift(rng, g.capacity as u64 + 1) as i64;
        }
        if s.fields[1][i] == 1 {
            s.fields[0][i] = 0;
        }
    }
    s
}

/// Outcome of `fluid_check`.
#[derive(Debug, Clone, PartialEq)]
pub struct FluidCheck {
    /// Cell-rule inputs compared with `fluid_cell`, and whether that covered all of them.
    pub local_cases: u64,
    pub local_exhaustive: bool,
    pub local_mismatches: u64,
    /// Random grids, each run for a number of steps, every step against `fluid_step`.
    pub grids: u64,
    pub steps: u64,
    pub step_mismatches: u64,
    /// Steps where total water changed, and where a cell left 0..capacity or a wall held water.
    pub mass_changes: u64,
    pub bound_violations: u64,
    pub hidden: Vec<usize>,
    pub conv_params: usize,
}

/// Compile a fluid program and check it: the cell network against `fluid_cell` on every
/// tap combination (or `local_limit` random ones), then `grids` random h x w grids for
/// `steps` steps each against `fluid_step`, with total water, bounds and walls checked.
#[allow(clippy::too_many_arguments)]
pub fn fluid_check(g: &FluidRule, src: &str, local_limit: u64, grids: u64, steps: u64, h: usize, w: usize, seed: u64) -> Result<FluidCheck> {
    let c = deep::compile(src, 1e-6)?;
    let s = deep::StencilWeights::from_compiled(&c).ok_or_else(|| WirError::new("not a grid program"))?;
    let mut net = deep::SparseNet::new(&s.net);
    let mut rng = seed.max(1);
    let sizes: Vec<u64> = s.taps.iter().map(|&(ch, _, _)| (g.span(ch).1 - g.span(ch).0 + 1) as u64).collect();
    let total = sizes.iter().try_fold(1u64, |a, &b| a.checked_mul(b));
    let local_exhaustive = total.is_some_and(|t| t <= local_limit);
    let local_cases = if local_exhaustive { total.unwrap() } else { local_limit };
    let mut local_mismatches = 0;
    let mut x = vec![0.0; s.taps.len()];
    for i in 0..local_cases {
        let mut k = i;
        for (t, &(ch, _, _)) in s.taps.iter().enumerate() {
            let n = sizes[t];
            let digit = if local_exhaustive {
                let d = k % n;
                k /= n;
                d
            } else {
                xorshift(&mut rng, n)
            };
            x[t] = (g.span(ch).0 + digit as i64) as f64;
        }
        let (m2, p2) = fluid_cell(g, |ch, dy, dx| match s.taps.iter().position(|&t| t == (ch, dy, dx)) {
            Some(t) => x[t] as i64,
            None => panic!("the rule reads channel {ch} at [{dy}, {dx}], which the program does not"),
        });
        let got = net.eval(&x);
        local_mismatches += ((got[0] - m2 as f64).abs() > 1e-6 || (got[1] - p2 as f64).abs() > 1e-6) as u64;
    }
    let (mut total_steps, mut step_mismatches, mut mass_changes, mut bound_violations) = (0, 0, 0, 0);
    for _ in 0..grids {
        let mut grid_rng = 1 + xorshift(&mut rng, u64::MAX - 1);
        let mut grid = fluid_random_grid(g, h, w, &mut grid_rng);
        let mass = grid.mass();
        for _ in 0..steps {
            let [m2, p2] = fluid_step(g, &grid);
            let got = s.apply_with(&mut net, &grid.inputs(), h, w);
            total_steps += 1;
            let same = |a: &[f64], b: &[i64]| a.iter().zip(b).all(|(a, b)| (a - *b as f64).abs() <= 1e-6);
            step_mismatches += !(same(&got[0], &m2) && same(&got[1], &p2)) as u64;
            grid.fields[0] = m2;
            grid.fields[2] = p2;
            mass_changes += (grid.mass() != mass) as u64;
            bound_violations +=
                grid.fields[0].iter().zip(&grid.fields[1]).any(|(&v, &wl)| v < 0 || v > g.capacity || (wl == 1 && v != 0)) as u64;
        }
    }
    Ok(FluidCheck {
        local_cases,
        local_exhaustive,
        local_mismatches,
        grids,
        steps: total_steps,
        step_mismatches,
        mass_changes,
        bound_violations,
        hidden: s.net.hidden(),
        conv_params: s.param_count(),
    })
}
